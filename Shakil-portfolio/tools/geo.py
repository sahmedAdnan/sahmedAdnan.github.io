"""Builds js/geo.js: a hexagonal dot lattice of the land between Western Europe and
Bangladesh, for the dotted map in the About section.
Source: Natural Earth 1:110m land via the world-atlas package (public domain).
    python tools/geo.py path/to/land-110m.json"""
import json
import math
import os
import sys

from PIL import Image, ImageDraw

LON0, LON1, LAT0, LAT1 = -12.0, 104.0, 4.0, 71.0      # crop
COSLAT = math.cos(math.radians(38))                  # equirectangular, standard parallel 38°N
STEP = 1.1                                           # lattice spacing, degrees of latitude
SCALE = 20                                           # raster pixels per degree

topo = json.load(open(sys.argv[1], encoding='utf-8'))
sx, sy = topo['transform']['scale']
tx, ty = topo['transform']['translate']
arcs = []
for arc in topo['arcs']:
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx; y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)


def ring(indices):
    out = []
    for i in indices:
        pts = arcs[i] if i >= 0 else arcs[~i][::-1]
        out.extend(pts if not out else pts[1:])
    return out


def project(lon, lat):
    return ((lon - LON0) * COSLAT * SCALE, (LAT1 - lat) * SCALE)


W = int((LON1 - LON0) * COSLAT * SCALE)
H = int((LAT1 - LAT0) * SCALE)
img = Image.new('L', (W, H), 0)
draw = ImageDraw.Draw(img)
for geom in topo['objects']['land']['geometries']:
    polys = geom['arcs'] if geom['type'] == 'MultiPolygon' else [geom['arcs']]
    for poly in polys:
        for k, r in enumerate(poly):
            pts = [project(lon, lat) for lon, lat in ring(r)]
            if len(pts) > 2:
                draw.polygon(pts, fill=255 if k == 0 else 0)

px = img.load()
dx = STEP * SCALE                                    # horizontal spacing in pixels
dy = STEP * SCALE * math.sqrt(3) / 2                 # hex row spacing
cols = int(W / dx)
rows = int(H / dy)
masks = []
for j in range(rows):
    bits = 0
    for i in range(cols):
        x = (i + 0.5 + (0.5 if j % 2 else 0)) * dx
        y = (j + 0.5) * dy
        if x < W and y < H and px[int(x), int(y)] > 127:
            bits |= 1 << i
    masks.append(format(bits, 'x'))


def city(lon, lat):
    x, y = project(lon, lat)
    return [round(x / dx - 0.5, 3), round(y / dy - 0.5, 3)]      # in lattice units


data = {
    'cols': cols, 'rows': rows, 'hex': math.sqrt(3) / 2, 'rowsHex': masks,
    'cities': {'Dhaka': city(90.41, 23.81), 'Aarhus': city(10.20, 56.16)},
}
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'js', 'geo.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* Dotted land lattice, Western Europe to Bangladesh. Natural Earth 1:110m (public domain),\n'
            '   generated by tools/geo.py. Each row is a hex bitmask over `cols` lattice columns. */\n')
    f.write('window.SA = window.SA || {};\nSA.geo = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print(cols, rows, sum(bin(int(m, 16)).count('1') for m in masks), 'land dots', os.path.getsize(out), 'bytes')
img.resize((W // 4, H // 4)).save(sys.argv[2] if len(sys.argv) > 2 else os.devnull, 'PNG') if len(sys.argv) > 2 else None
