// Refreshes js/works-snapshot.js, the offline fallback for the publication list.
// The live site already updates itself from ORCID, OpenAlex and Crossref; run this
// occasionally so the fallback stays close:   node tools/snapshot.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
await import(pathToFileURL(join(here, '../js/works.js')).href);
const data = await globalThis.SA.works.fetchLive(fetch);
if (data.partial) { console.error('OpenAlex could not be reached; the snapshot was left as it is.'); process.exit(1); }
const out = `/* Generated by tools/snapshot.mjs on ${new Date().toISOString().slice(0, 10)}. Fallback only. */\n`
  + `window.SA = window.SA || {};\nSA.worksSnapshot = ${JSON.stringify(data)};\n`;
writeFileSync(join(here, '../js/works-snapshot.js'), out);
console.log(`${data.works.length} works written`);
